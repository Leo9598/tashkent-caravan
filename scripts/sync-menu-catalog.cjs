const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
const start = source.indexOf('  const menuData = [');
const end = source.indexOf('  // DOM Elements', start);
if (start < 0 || end < 0) throw new Error('Menu source not found');
const menu = vm.runInNewContext(source.slice(start, end) + '\nmenuData;', {}, { timeout: 1000 });
const catalog = menu.map(({ id, price, ro, firstCourses, secondCourses, additional, isBusinessLunch }) => ({ id, price, name: ro.name, ...(isBusinessLunch ? { isBusinessLunch, firstCourses, secondCourses, additional } : {}) }));
const output = '// Generated by scripts/sync-menu-catalog.cjs; keep in sync with app.js.\nexport default ' + JSON.stringify(catalog, null, 2) + ';\n';
const target = path.join(root, 'server/menu-catalog.mjs');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Run npm run sync-menu before committing menu changes');
} else fs.writeFileSync(target, output);
